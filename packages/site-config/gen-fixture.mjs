#!/usr/bin/env node
// Writes an Elm module holding the resolver's output for a config.toml as a
// JSON string, so Elm tests run against what the resolver really produces.
//
// usage: gen-fixture.mjs [--config <config.toml>] [--out <File.elm>] [--check]
//
// Without arguments it writes the hub's own tests/SiteSettingsFixture.elm from
// fixtures/bilingual.toml. An app generates its own fixture from its config:
//
//   node vendor/master-builder/packages/site-config/gen-fixture.mjs \
//     --config config.toml --out elm-app/tests/SiteFixture.elm
//
// `--check` fails when the file is out of date instead of writing it. The year
// is pinned so the fixture does not change on New Year's Day.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, relative, resolve } from 'node:path'
import { load, SiteConfigError } from './site-config.mjs'

// A configuration problem is the user's to fix: print it, not a stack trace.
function loadOrExit(path, options) {
  try {
    return load(path, options)
  } catch (error) {
    if (!(error instanceof SiteConfigError)) throw error
    console.error(`${path}: ${error.message}`)
    process.exit(1)
  }
}

const here = (path) => new URL(path, import.meta.url).pathname
const option = (name, fallback) => {
  const index = process.argv.indexOf(name)
  return index === -1 ? fallback : resolve(process.argv[index + 1])
}

const config = option('--config', here('./fixtures/bilingual.toml'))
const target = option('--out', here('../../tests/SiteSettingsFixture.elm'))
const module = basename(target, '.elm')
const json = JSON.stringify(loadOrExit(config, { year: 2026 }))
const elm = `module ${module} exposing (json)

{-| Generated by packages/site-config/gen-fixture.mjs from ${basename(config)}. Do not edit.
-}


{-| The resolver's output for ${basename(config)}, with the year pinned to 2026.
-}
json : String
json =
    ${JSON.stringify(json)}
`
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== elm) {
    console.error(`${relative(process.cwd(), target)} is out of date; regenerate it with gen-fixture.mjs`)
    process.exit(1)
  }
} else {
  writeFileSync(target, elm)
}
