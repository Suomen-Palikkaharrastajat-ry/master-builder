#!/usr/bin/env node
// Writes packages/app-toolkit/tests/LocaleNames.elm from locales.json, so the
// Elm `Locale` and the Haskell generators (gen-haskell.mjs) are held to one
// table of month and weekday names. `--check` fails when it is out of date.
import { readFileSync, writeFileSync } from 'node:fs'

const here = (path) => new URL(path, import.meta.url).pathname
const locales = JSON.parse(readFileSync(here('./locales.json'), 'utf8'))
const list = (items) => '[ ' + items.map((item) => JSON.stringify(item)).join(', ') + ' ]'
const entries = Object.entries(locales).map(
  ([lang, names]) => `( ${JSON.stringify(lang)}, { months = ${list(names.months)}, weekdays = ${list(names.weekdays)} } )`,
)
const elm = `module LocaleNames exposing (names)

{-| Generated by packages/site-config/gen-locale-fixture.mjs from locales.json. Do not edit.

i18n-exempt: generated from locales.json, where the names live.

-}


{-| Month names (January first) and weekday abbreviations (Monday first) per
language code.
-}
names : List ( String, { months : List String, weekdays : List String } )
names =
    [ ${entries.join('\n    , ')}
    ]
`
const target = here('../app-toolkit/tests/LocaleNames.elm')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== elm) {
    console.error('packages/app-toolkit/tests/LocaleNames.elm is out of date; run node packages/site-config/gen-locale-fixture.mjs')
    process.exit(1)
  }
} else {
  writeFileSync(target, elm)
}
